def parse_extension_officer_markdown(text: str) -> Dict[str, Any]:
    """
    Parses the exact 5 structured markdown blocks generated by the Extension Officer prompt.
    Returns normalized dictionary with parsed entities and the original raw markdown.
    """
    res = {
        "raw_markdown": text.strip() if text else "",
        "crop_name": "Agricultural Crop",
        "disease_name": "Crop Health Condition",
        "confidence": 0.92,
        "observed_symptoms": "",
        "differential_candidates": [],
        "biological_advisory": {
            "field_cleanup": "Prune and safely burn or bury severely infected lower foliage to reduce local inoculum.",
            "water_management": "Avoid overhead sprinkler irrigation; switch to drip watering to keep foliage dry.",
            "organic_spray": "Spray cold-pressed neem oil (10,000 ppm) @ 5 ml/L with mild surfactant or Trichoderma viride @ 5 g/L."
        },
        "pro_chemical_plan": {
            "targeted_solution": "Apply standard protectant fungicide (Mancozeb 75% WP or Copper Oxychloride 50% WP @ 2.5 g/L).",
            "alternative_compound": "Systemic alternative (Azoxystrobin 18.2% + Difenoconazole 11.4% SC @ 1 ml/L or Hexaconazole 5% EC @ 2 ml/L).",
            "prevention_routine": "Spray neighboring healthy border plants within 48 hours to create a protective chemical buffer."
        },
        "label_verification": "Make sure to double-check the physical product label container to confirm that the product names, active concentrations, and biometric dosage values are completely accurate before execution in the field!"
    }
    if not text:
        return res

    # 1. Host Plant / Crop
    crop_m = re.search(r"-\s*\*\*Host Plant/Crop\*\*:\s*([^\n\r]+)", text, re.IGNORECASE)
    if crop_m:
        res["crop_name"] = crop_m.group(1).strip().strip("[]").title()

    # 2. Primary Diagnosis
    diag_m = re.search(r"-\s*\*\*Primary Diagnosis\*\*:\s*([^\n\r]+)", text, re.IGNORECASE)
    if diag_m:
        res["disease_name"] = diag_m.group(1).strip().strip("[]").title()

    # 3. Confidence Rating
    conf_m = re.search(r"-\s*\*\*Confidence Rating\*\*:\s*([^\n\r]+)", text, re.IGNORECASE)
    if conf_m:
        c_str = conf_m.group(1).strip()
        num_m = re.search(r"(\d+(?:\.\d+)?)", c_str)
        if num_m:
            raw_pct = float(num_m.group(1))
            res["confidence"] = raw_pct / 100.0 if raw_pct > 1.0 else raw_pct

    # 4. Observed Symptoms
    sym_m = re.search(r"-\s*\*\*Observed Symptoms\*\*:\s*([^\n\r]+(?:\n(?!\s*###|\s*-|\s*\d+\.).*)*)", text, re.IGNORECASE)
    if sym_m:
        clean_sym = re.sub(r"\s+", " ", sym_m.group(1).strip()).strip("[]")
        res["observed_symptoms"] = clean_sym

    # 5. Differential Candidates (extract up to 3)
    diff_block_m = re.search(r"###\s*🩹\s*DIFFERENTIAL DIAGNOSIS[\s\S]*?(?=###|\Z)", text, re.IGNORECASE)
    if diff_block_m:
        diff_text = diff_block_m.group(0)
        items = re.findall(r"\d+\.\s*\*\*([^*]+)\*\*:\s*([^\n\r]+)", diff_text)
        candidates = []
        for idx, (cand_name, trait_desc) in enumerate(items[:3]):
            clean_name = cand_name.strip().strip("[]")
            clean_trait = trait_desc.strip().strip("[]")
            cand_conf = max(0.20, (res["confidence"] if idx == 0 else (res["confidence"] * (0.85 - idx * 0.12))))
            candidates.append({
                "disease_name": clean_name,
                "crop_name": res["crop_name"],
                "confidence": round(cand_conf * 100, 1),
                "visual_hallmark": clean_trait
            })
        if candidates:
            res["differential_candidates"] = candidates

    # 6. Biological Advisory
    bio_block_m = re.search(r"###\s*🌿\s*BIOLOGICAL ADVISORY[\s\S]*?(?=###|\Z)", text, re.IGNORECASE)
    if bio_block_m:
        bio_text = bio_block_m.group(0)
        cu_m = re.search(r"\d+\.\s*\*\*Field Cleanup\*\*:\s*([^\n\r]+)", bio_text, re.IGNORECASE)
        wm_m = re.search(r"\d+\.\s*\*\*Water Management\*\*:\s*([^\n\r]+)", bio_text, re.IGNORECASE)
        os_m = re.search(r"\d+\.\s*\*\*Organic Spray\*\*:\s*([^\n\r]+)", bio_text, re.IGNORECASE)
        if cu_m:
            res["biological_advisory"]["field_cleanup"] = cu_m.group(1).strip().strip("[]")
        if wm_m:
            res["biological_advisory"]["water_management"] = wm_m.group(1).strip().strip("[]")
        if os_m:
            res["biological_advisory"]["organic_spray"] = os_m.group(1).strip().strip("[]")

    # 7. Pro Chemical Action Plan
    chem_block_m = re.search(r"###\s*🧪\s*PRO CHEMICAL ACTION PLAN[\s\S]*?(?=⚠️|\Z)", text, re.IGNORECASE)
    if chem_block_m:
        chem_text = chem_block_m.group(0)
        ta_m = re.search(r"\d+\.\s*\*\*Targeted Active Solution\*\*:\s*([^\n\r]+)", chem_text, re.IGNORECASE)
        ac_m = re.search(r"\d+\.\s*\*\*Alternative Compound\*\*:\s*([^\n\r]+)", chem_text, re.IGNORECASE)
        pr_m = re.search(r"\d+\.\s*\*\*Prevention Routine\*\*:\s*([^\n\r]+)", chem_text, re.IGNORECASE)
        if ta_m:
            res["pro_chemical_plan"]["targeted_solution"] = ta_m.group(1).strip().strip("[]")
        if ac_m:
            res["pro_chemical_plan"]["alternative_compound"] = ac_m.group(1).strip().strip("[]")
        if pr_m:
            res["pro_chemical_plan"]["prevention_routine"] = pr_m.group(1).strip().strip("[]")

    return res

