async def cross_verify_disease_with_vision(
    image_path: str,
    crop_hint: Optional[str] = None
) -> Optional[Dict[str, Any]]:
    """
    Expert multimodal diagnosis using the official Agricultural Extension Officer & Plant Pathologist prompt.
    Analyzes visible plant anomalies and parses the 5 structured markdown blocks.
    """
    gemini_key = getattr(settings, "GEMINI_API_KEY", "")
    if not gemini_key or "mock" in gemini_key or "PASTE" in gemini_key:
        logger.debug("Gemini API key not configured for Extension Officer vision.")
        return None

    if not os.path.exists(image_path):
        logger.warning(f"Image path for Gemini vision does not exist: {image_path}")
        return None

    try:
        with open(image_path, "rb") as f:
            image_bytes = f.read()
        b64_img = base64.b64encode(image_bytes).decode("utf-8")

        prompt = EXTENSION_OFFICER_PROMPT
        if crop_hint:
            prompt += f"\n\nContext Hint: The farmer indicates this plant is {crop_hint}."

        payload = {
            "contents": [{
                "parts": [
                    {"text": prompt},
                    {"inline_data": {"mime_type": "image/jpeg", "data": b64_img}}
                ]
            }],
            "generationConfig": {
                "temperature": 0.1,
                "maxOutputTokens": 1024
            }
        }

        models_to_try = ["gemini-flash-lite-latest", "gemini-flash-latest"]
        async with httpx.AsyncClient(timeout=14.0) as client:
            for model_name in models_to_try:
                try:
                    url = f"https://generativelanguage.googleapis.com/v1beta/models/{model_name}:generateContent?key={gemini_key}"
                    resp = await client.post(url, json=payload)
                    if resp.status_code == 200:
                        data = resp.json()
                        candidates = data.get("candidates", [])
                        if candidates:
                            parts = candidates[0].get("content", {}).get("parts", [])
                            if parts:
                                raw_text = "".join([p.get("text", "") for p in parts]).strip()
                                parsed = parse_extension_officer_markdown(raw_text)
                                if parsed and parsed.get("disease_name") and parsed["disease_name"] != "Crop Health Condition":
                                    logger.info(f"Gemini Extension Officer diagnosis succeeded with model {model_name}")
                                    return parsed
                except Exception as m_err:
                    logger.debug(f"Gemini model {model_name} extension officer attempt: {m_err}")
                    continue

    except Exception as e:
        logger.warning(f"Gemini Extension Officer vision diagnosis failed: {e}")

    return None

