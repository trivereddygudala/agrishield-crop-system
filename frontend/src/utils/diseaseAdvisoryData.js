export function localizeAdvice(str, lang = 'en') {
  if (!str) return '';
  const cleanLang = (lang ? lang.split('-')[0] : 'en').toLowerCase();
  if (cleanLang !== 'te' || /[\u0C00-\u0C7F]/.test(str)) return str;
  const lower = String(str).toLowerCase();
  for (const [key, translated] of Object.entries(TELUGU_ADVICE_MAP)) {
    if (lower.includes(key)) {
      return translated;
    }
  }
  return str;
}

export function localizeCalendarItem(item, lang = 'en') {
  if (!item) return item;
  const cleanLang = (lang ? lang.split('-')[0] : 'en').toLowerCase();
  if (cleanLang !== 'te') return item;
  return {
    ...item,
    title: localizeAdvice(item.title, 'te') || item.title,
    activity: localizeAdvice(item.activity, 'te') || item.activity
  };
}


