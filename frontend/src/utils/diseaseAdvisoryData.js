// Common disease matching key normalizer
export function normalizeDiseaseKey(rawName = '') {
  const str = String(rawName).toLowerCase().trim();
  if (str.includes('early blight') || str.includes('ఆల్టర్నేరియా') || str.includes('ముందస్తు')) return 'early blight';
  if (str.includes('late blight') || str.includes('లేట్ బ్లైట్') || str.includes('पछेती')) return 'late blight';
  if (str.includes('target spot') || str.includes('లక్ష్యపు') || str.includes('टारगेट')) return 'target spot';
  if (str.includes('bacterial') || str.includes('బ్యాక్టీరియ') || str.includes('जीवाणु')) return 'bacterial spot';
  if (str.includes('rust') || str.includes('తుప్పు') || str.includes('गेरुई') || str.includes('रतुआ')) return 'common rust';
  if (str.includes('curl') || str.includes('ముడత') || str.includes('मरोड़')) return 'leaf curl virus';
  if (str.includes('healthy') || str.includes('ఆరోగ్య') || str.includes('स्वस्थ')) return 'healthy';
  return 'early blight'; // fallback default structured plan
}

export function getDiseaseDetails(cropName, diseaseName, lang = 'en') {
  const key = normalizeDiseaseKey(diseaseName);
  const kbEntry = DISEASE_KB[key] || DISEASE_KB['early blight'];
  const language = (lang === 'te' || lang === 'hi') ? lang : 'en';
  const data = kbEntry[language] || kbEntry.en;
  return {
    ...data,
    key,
    isHealthy: key === 'healthy'
  };
}

